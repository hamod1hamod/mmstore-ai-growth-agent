import React, { useState } from 'react';
import { Sidebar, NavTab } from './components/Sidebar';
import { Header } from './components/Header';
import { OverviewView } from './views/OverviewView';
import { AIMarketingAgentView } from './views/AIMarketingAgentView';
import { ContentStudioView } from './views/ContentStudioView';
import { VideoStudioView } from './views/VideoStudioView';
import { CalendarView } from './views/CalendarView';
import { SocialAccountsView } from './views/SocialAccountsView';
import { CampaignsView } from './views/CampaignsView';
import { AnalyticsView } from './views/AnalyticsView';
import { FinancialGrowthView } from './views/FinancialGrowthView';
import { CustomerInboxView } from './views/CustomerInboxView';
import { ProductCatalogView } from './views/ProductCatalogView';
import { AutomationRulesView } from './views/AutomationRulesView';
import { NotificationsView } from './views/NotificationsView';
import { TeamPermissionsView } from './views/TeamPermissionsView';
import { SettingsView } from './views/SettingsView';
import { SubscriptionPlanView } from './views/SubscriptionPlanView';

import { 
  MOCK_PRODUCTS, 
  MOCK_SOCIAL_ACCOUNTS, 
  MOCK_POSTS, 
  MOCK_AUTOPILOT_CONFIG, 
  MOCK_CAMPAIGN_FINANCES, 
  MOCK_CUSTOMER_CONVERSATIONS 
} from './services/mockData';
import { Product, Post, SocialAccount, AutopilotConfig, PlatformId, OrgSubscription, SubscriptionTier } from './types';

export const App: React.FC = () => {
  const [activeTab, setActiveTab] = useState<NavTab>('overview');
  const [products, setProducts] = useState<Product[]>(MOCK_PRODUCTS);
  const [posts, setPosts] = useState<Post[]>(MOCK_POSTS);
  const [accounts, setAccounts] = useState<SocialAccount[]>(MOCK_SOCIAL_ACCOUNTS);
  const [autopilotConfig, setAutopilotConfig] = useState<AutopilotConfig>(MOCK_AUTOPILOT_CONFIG);
  const [finances, setFinances] = useState(MOCK_CAMPAIGN_FINANCES);
  const [conversations, setConversations] = useState(MOCK_CUSTOMER_CONVERSATIONS);
  const [isAutopilotRunning, setIsAutopilotRunning] = useState<boolean>(false);
  const [subscription, setSubscription] = useState<OrgSubscription>({
    orgId: 'default-mmstore',
    tier: 'growth',
    status: 'active',
    currentPeriodEnd: Date.now() + 30 * 86400000,
    githubUser: 'Mohamedamdouh',
    usageThisMonth: {
      postsPublished: 18,
      videoSecondsRendered: 270,
      aiCopyGenerations: 45,
    },
  });

  // Trigger Autopilot daily cycle
  const handleTriggerAutopilotNow = () => {
    setIsAutopilotRunning(true);
    setTimeout(() => {
      // Create new autonomous post for today
      const randomProduct = products[Math.floor(Math.random() * products.length)];
      const newPost: Post = {
        id: `auto_${Date.now()}`,
        orgId: 'default-mmstore',
        productId: randomProduct.id,
        title: `${randomProduct.name} - Autopilot Daily Drop`,
        captionArabic: `الستايل اللي كل الناس بتسأل عليه متوفر دلوقتي في MMStore! 🔥 خامة قطن مصري 100% تقيل، فيت مظبوط وشحن سريع لجميع المحافظات والدفع بعد المعاينة!`,
        captionEnglish: `Fresh drop from MMStore! ${randomProduct.name} available now in all sizes. Order online with cash on delivery available.`,
        hashtags: ['#MMStore', '#StreetwearEgypt', '#CairoFashion', '#ملابس_شبابية'],
        platforms: autopilotConfig.targetPlatforms,
        format: 'reel',
        aspectRatio: '9:16',
        mediaUrls: randomProduct.images,
        productUrl: randomProduct.productUrl,
        utmParams: {
          utm_source: 'autopilot_daily',
          utm_medium: 'reel',
          utm_campaign: `daily_drop_${new Date().toISOString().split('T')[0]}`,
          utm_content: randomProduct.id,
        },
        status: autopilotConfig.requireApproval ? 'awaiting_approval' : 'published',
        scheduledTime: Date.now(),
        publishedAt: autopilotConfig.requireApproval ? undefined : Date.now(),
        idempotencyKey: `auto_idemp_${Date.now()}`,
        retryCount: 0,
        autoGenerated: true,
        requiresHumanApproval: autopilotConfig.requireApproval,
        createdAt: Date.now(),
        updatedAt: Date.now(),
      };

      setPosts(prev => [newPost, ...prev]);
      setIsAutopilotRunning(false);
      alert(`⚡ Autopilot Cycle Complete! Generated and published Reel for "${randomProduct.name}" across ${autopilotConfig.targetPlatforms.join(', ')}.`);
    }, 1200);
  };

  const handleToggleAutopilot = () => {
    setAutopilotConfig(prev => ({ ...prev, enabled: !prev.enabled }));
  };

  const handleSchedulePost = (newPost: Post) => {
    setPosts(prev => [newPost, ...prev]);
    setActiveTab('calendar');
  };

  const handlePublishNow = (newPost: Post, platform: PlatformId) => {
    const publishedPost: Post = {
      ...newPost,
      status: 'published',
      publishedAt: Date.now(),
    };
    setPosts(prev => [publishedPost, ...prev]);
    alert(`🎉 Successfully published to ${platform.toUpperCase()}! Post is live.`);
    setActiveTab('overview');
  };

  const handleRetryPost = (postId: string) => {
    setPosts(prev => prev.map(p => {
      if (p.id === postId) {
        return { ...p, status: 'published', failureReason: undefined, publishedAt: Date.now() };
      }
      return p;
    }));
    alert('Post retry succeeded! Marked as Published.');
  };

  const handleApprovePost = (postId: string) => {
    setPosts(prev => prev.map(p => {
      if (p.id === postId) {
        return { ...p, status: 'scheduled', requiresHumanApproval: false };
      }
      return p;
    }));
    alert('Post approved! Moved to scheduled queue.');
  };

  const handleToggleAccount = (accId: string) => {
    setAccounts(prev => prev.map(a => {
      if (a.id === accId) {
        return { ...a, connected: !a.connected, status: !a.connected ? 'healthy' : 'disconnected' };
      }
      return a;
    }));
  };

  const handleSendReply = (convoId: string, replyText: string) => {
    setConversations(prev => prev.map(c => {
      if (c.id === convoId) {
        return { ...c, status: 'resolved', unreadCount: 0 };
      }
      return c;
    }));
  };

  const tabTitles: Record<NavTab, string> = {
    overview: '1. Executive Overview & Autopilot Pilot',
    agent: '2. AI Marketing Agent Coordinator',
    'content-studio': '3. AI Product-to-Content Studio',
    'video-studio': '4. AI Video & Reels Studio (9:16 Vertical)',
    calendar: '5. Social Media Calendar & Scheduler',
    accounts: '6. Social Accounts & Capability Registry',
    campaigns: '7. Marketing Campaigns & A/B Experiments',
    analytics: '8. AI-Powered Marketing Analytics',
    financials: '9. Financial Growth Engine & ROAS',
    inbox: '10. Customer Engagement Inbox',
    catalog: '11. Fashion Catalog & Inventory',
    automation: '12. Social Automation Rules & Limits',
    notifications: '13. Notifications & Activity Stream',
    team: '14. Team Roles & Immutable Audit Trail',
    settings: '15. Brand Kit, Voice & Secrets',
    subscription: '16. Subscription & GitHub Marketplace Plans',
  };

  return (
    <div className="flex h-screen w-screen overflow-hidden bg-[#0d0f12] text-slate-100 font-sans">
      {/* Sidebar navigation */}
      <Sidebar
        activeTab={activeTab}
        setActiveTab={setActiveTab}
        autopilotEnabled={autopilotConfig.enabled}
        onToggleAutopilot={handleToggleAutopilot}
      />

      {/* Main Content Area */}
      <div className="flex-1 flex flex-col min-w-0 overflow-hidden">
        <Header
          autopilotEnabled={autopilotConfig.enabled}
          onTriggerAutopilotNow={handleTriggerAutopilotNow}
          isAutopilotRunning={isAutopilotRunning}
          activeTabTitle={tabTitles[activeTab]}
        />

        <main className="flex-1 overflow-y-auto p-4 sm:p-6 lg:p-8">
          <div className="max-w-7xl mx-auto pb-12">
            {activeTab === 'overview' && (
              <OverviewView
                products={products}
                posts={posts}
                accounts={accounts}
                finances={finances}
                autopilotEnabled={autopilotConfig.enabled}
                onNavigate={setActiveTab}
                onTriggerAutopilot={handleTriggerAutopilotNow}
              />
            )}

            {activeTab === 'agent' && (
              <AIMarketingAgentView
                autopilotConfig={autopilotConfig}
                onUpdateConfig={setAutopilotConfig}
                onRunAutopilotNow={handleTriggerAutopilotNow}
                isRunning={isAutopilotRunning}
              />
            )}

            {activeTab === 'content-studio' && (
              <ContentStudioView
                products={products}
                onSchedulePost={handleSchedulePost}
                onPublishNow={handlePublishNow}
              />
            )}

            {activeTab === 'video-studio' && (
              <VideoStudioView
                products={products}
              />
            )}

            {activeTab === 'calendar' && (
              <CalendarView
                posts={posts}
                onRetryPost={handleRetryPost}
                onApprovePost={handleApprovePost}
              />
            )}

            {activeTab === 'accounts' && (
              <SocialAccountsView
                accounts={accounts}
                onToggleAccount={handleToggleAccount}
              />
            )}

            {activeTab === 'campaigns' && (
              <CampaignsView
                finances={finances}
              />
            )}

            {activeTab === 'analytics' && (
              <AnalyticsView
                posts={posts}
                finances={finances}
              />
            )}

            {activeTab === 'financials' && (
              <FinancialGrowthView
                finances={finances}
                products={products}
              />
            )}

            {activeTab === 'inbox' && (
              <CustomerInboxView
                conversations={conversations}
                onSendReply={handleSendReply}
              />
            )}

            {activeTab === 'catalog' && (
              <ProductCatalogView
                products={products}
                onSelectForContent={(prod) => {
                  setActiveTab('content-studio');
                }}
              />
            )}

            {activeTab === 'automation' && (
              <AutomationRulesView
                config={autopilotConfig}
                onSave={setAutopilotConfig}
              />
            )}

            {activeTab === 'notifications' && (
              <NotificationsView />
            )}

            {activeTab === 'team' && (
              <TeamPermissionsView />
            )}

            {activeTab === 'settings' && (
              <SettingsView />
            )}

            {activeTab === 'subscription' && (
              <SubscriptionPlanView
                currentSubscription={subscription}
                onUpgradePlan={(newTier) => setSubscription(prev => ({ ...prev, tier: newTier }))}
              />
            )}
          </div>
        </main>
      </div>
    </div>
  );
};

export default App;
